-- Convert all surrogate keys to PostgreSQL BIGINT autoincrement columns.
-- Existing Phase and Report numeric keys and their references are preserved.

ALTER TABLE "Phase" ALTER COLUMN "id" DROP DEFAULT;
ALTER TABLE "Phase" ALTER COLUMN "id" TYPE BIGINT;
ALTER TABLE "Phase" ALTER COLUMN "id" SET NOT NULL;
ALTER SEQUENCE "Phase_id_seq" AS BIGINT;
ALTER TABLE "Phase" ALTER COLUMN "id" SET DEFAULT nextval('"Phase_id_seq"');
SELECT setval('"Phase_id_seq"', COALESCE((SELECT MAX("id") FROM "Phase"), 0) + 1, false);

ALTER TABLE "Report" ALTER COLUMN "id" DROP DEFAULT;
ALTER TABLE "Report" ALTER COLUMN "id" TYPE BIGINT;
ALTER TABLE "Report" ALTER COLUMN "phaseId" TYPE BIGINT;

ALTER SEQUENCE "Report_id_seq" AS BIGINT;
ALTER TABLE "Report" ALTER COLUMN "id" SET DEFAULT nextval('"Report_id_seq"');
SELECT setval('"Report_id_seq"', COALESCE((SELECT MAX("id") FROM "Report"), 0) + 1, false);

